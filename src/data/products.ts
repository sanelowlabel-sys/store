export const SUPPORTED_CURRENCIES: Record<CurrencyCode, CurrencyConfig> = {
  USD: { code: 'USD', symbol: '$', rateFromUSD: 1.0, label: 'USD ($)' },
  EUR: { code: 'EUR', symbol: '€', rateFromUSD: 0.92, label: 'EUR (€)' },
  GBP: { code: 'GBP', symbol: '£', rateFromUSD: 0.79, label: 'GBP (£)' },
  ZAR: { code: 'ZAR', symbol: 'R', rateFromUSD: 18.2, label: 'ZAR (R)' },
  CAD: { code: 'CAD', symbol: 'CA$', rateFromUSD: 1.36, label: 'CAD ($)' },
  AUD: { code: 'AUD', symbol: 'AU$', rateFromUSD: 1.52, label: 'AUD ($)' },
};

export const formatPrice = (priceUSD: number, currency: CurrencyCode = 'USD'): string => {
  const config = SUPPORTED_CURRENCIES[currency] || SUPPORTED_CURRENCIES.USD;
  const converted = priceUSD * config.rateFromUSD;

  if (currency === 'ZAR') {
    return `${config.symbol} ${Math.round(converted).toLocaleString()}`;
  }
  return `${config.symbol}${converted.toFixed(2)}`;
};

